// Regenerate tests/fixtures/jcs-parity.json from the Worker's own canonicalizer.
//
// The fixture is the contract between the two implementations of RFC 8785 in
// this repository: `jcs()` in deploy/cloudflare-worker/src/jws.js, which the
// hosted Gate hashes with, and `agenda_intelligence.canonical`, which an
// enforcing Python caller computes its expected hashes with. If the two ever
// disagree, `decision_verify` answers `binding_mismatch` for a request that is
// in fact identical, and the Gate refuses a legitimate action.
//
//   node scripts/generate-jcs-parity-fixture.mjs
//
// Run it after touching either implementation and commit the result.

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { jcs } from "../deploy/cloudflare-worker/src/jws.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

// Cases are chosen for where the two languages disagree by default, not for
// coverage of JSON. Every "python_json_dumps_differs" case below is one where
// json.dumps(sort_keys=True) — what services._input_digest uses — produces a
// different string than JCS does.
const CASES = {
  pre_action_request: {
    actor: "ops-bot",
    requested_action: "release_payment",
    target: "counterparty-4471",
    risk_tier: "high",
    run_id: "run-2026-09-02-001"
  },
  whole_number_float: { threshold: 9.0 },
  whole_number_int: { threshold: 9 },
  negative_zero: { adjustment: -0.0 },
  large_magnitude: { amount: 1e22 },
  fixed_notation_boundary: { amount: 1e20 },
  exponential_boundary: { amount: 1e21 },
  small_magnitude: { ratio: 1e-7 },
  small_magnitude_fixed: { ratio: 1e-6 },
  ratio: { ratio: 1 / 3 },
  cyrillic_actor: { actor: "Айдын Жумабай" },
  arabic_target: { target: "مصرف الراجحي" },
  mixed_script: { actor: "Aktau Holdings ЖШС", target: "شركة" },
  nested_and_null: { b: [1, { z: "y", a: "b" }], a: null },
  empty_containers: { list: [], object: {}, text: "" },
  escapes: { text: 'quote " backslash \\ tab \t newline \n control \u0001 del \u007f' },
  // U+1F600 is a surrogate pair (D83D DE00) and U+FFFD is a single code unit, so
  // UTF-16 order puts the emoji first while Python's code-point order puts it last.
  // The fixture pins the UTF-16 answer, which is the one RFC 8785 requires.
  astral_key_ordering: { "\u{1F600}": 1, "�": 2, a: 3 },
  bmp_key_ordering: { "é": 1, z: 2, "éx": 3, "": 4 },
  booleans: { yes: true, no: false, nothing: null }
};

const fixture = {
  _comment:
    "Generated by scripts/generate-jcs-parity-fixture.mjs from deploy/cloudflare-worker/src/jws.js. Do not hand-edit.",
  cases: Object.fromEntries(
    Object.entries(CASES).map(([name, value]) => [
      name,
      {
        value,
        jcs: jcs(value),
        digest: "sha256:" + createHash("sha256").update(jcs(value), "utf8").digest("hex")
      }
    ])
  )
};

const target = join(ROOT, "tests", "fixtures", "jcs-parity.json");
writeFileSync(target, JSON.stringify(fixture, null, 2) + "\n", "utf8");
console.log(`wrote ${Object.keys(CASES).length} cases to ${target}`);
