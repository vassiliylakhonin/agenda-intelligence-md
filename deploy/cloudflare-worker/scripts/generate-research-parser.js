import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
const result=await build({entryPoints:[new URL('../apps/research/pdf-engine.js',import.meta.url).pathname],bundle:true,minify:true,format:'esm',platform:'browser',write:false,legalComments:'inline'});
const output='// Generated by scripts/generate-research-parser.js; do not edit. PDF.js license notices retained.\n'+result.outputFiles[0].text;
const target=new URL('../src/research-pdf-engine-bundle.js',import.meta.url);
if(process.argv.includes('--check')) {
  if(await readFile(target,'utf8').catch(()=>'')!==output)throw Error('Research PDF parser is stale; run node scripts/generate-research-parser.js');
}else await writeFile(target,output);
