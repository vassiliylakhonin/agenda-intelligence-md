import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
for(const kind of ['pdf','docx']) {
  const result=await build({entryPoints:[new URL('../apps/research/'+kind+'-engine.js',import.meta.url).pathname],bundle:true,minify:true,format:'esm',platform:'browser',write:false,legalComments:'inline'});
  const output='// Generated by scripts/generate-research-parser.js; do not edit. Dependency license notices retained.\n'+result.outputFiles[0].text;
  const target=new URL('../src/research-'+kind+'-engine-bundle.js',import.meta.url);
  if(process.argv.includes('--check')) {
    if(await readFile(target,'utf8').catch(()=>'')!==output)throw Error('Research '+kind+' parser is stale; run node scripts/generate-research-parser.js');
  }else await writeFile(target,output);
}
