import {build} from 'esbuild';
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const bundle=await build({entryPoints:[new URL('apps/answer-review/main.js',root).pathname],bundle:true,
  platform:'browser',format:'iife',target:'es2022',minify:true,legalComments:'inline',write:false});
const script=bundle.outputFiles[0].text.replaceAll('</script','<\\/script');
const html=readFileSync(new URL('apps/answer-review/index.html',root),'utf8').replace('/* APP_BUNDLE */',()=>script);
const content='// Generated by scripts/generate-answer-review-app.js; official MCP Apps SDK bundled at build time.\nexport const ANSWER_REVIEW_HTML='+JSON.stringify(html)+';\n';
const output=new URL('src/answer-review-html.js',root);
if(process.argv.includes('--check')) {
  if(readFileSync(output,'utf8')!==content){console.error('Answer review App is stale; run node scripts/generate-answer-review-app.js');process.exitCode=1;}
}else{writeFileSync(output,content);console.log('Bundled answer review App: '+new TextEncoder().encode(html).length+' bytes');}
