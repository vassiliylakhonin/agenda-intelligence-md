import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..", "..", "..");
const workerRoot = join(__dirname, "..");

const okfFiles = [
  "index.md",
  "ai-vendor-evidence-readiness.md",
  "human-review-packet.md",
  "evidence-pack.md",
  "claim-audit.md",
  "source-policy.md",
  "market-gate.md",
  "repo-stack.md"
];

function asciiJson(value) {
  return JSON.stringify(value, null, 2).replace(/[\u007f-\uffff]/g, (character) => {
    const code = character.charCodeAt(0).toString(16).padStart(4, "0");
    return `\\u${code}`;
  });
}

const content = Object.fromEntries(
  okfFiles.map((fileName) => {
    const markdown = readFileSync(join(repoRoot, "okf", fileName), "utf8");
    return [`/okf/${fileName}`, markdown];
  })
);

const output = `// Generated by scripts/generate-okf-content.js. Do not edit by hand.\n\nexport const OKF_CONTENT = Object.freeze(${asciiJson(
  content
)});\n\nexport const OKF_PATHS = Object.freeze(${asciiJson(Object.keys(content))});\n`;

writeFileSync(join(workerRoot, "src", "okf_content.js"), output);
