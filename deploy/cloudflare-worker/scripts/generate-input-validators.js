import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {build} from 'esbuild';
import {validationCatalog,validatorKey} from '../src/validation-catalog.js';
import {TRIAL_PROFILES} from '../src/trial-profiles.js';
const root=fileURLToPath(new URL('../',import.meta.url));
const ajv=new Ajv2020({strict:false,allErrors:true,coerceTypes:false,useDefaults:false,removeAdditional:false,code:{source:true}});
addFormats(ajv);
const names={},unique=new Map();
for(const profile of Object.keys(TRIAL_PROFILES)) for(const {name,schema} of validationCatalog(profile)) {
 const key=validatorKey(profile,name),copy=structuredClone(schema);
 delete copy.$id;
 const fingerprint=JSON.stringify(copy);
 if(!unique.has(fingerprint)) {copy.$id='urn:agenda:preflight:'+key;ajv.addSchema(copy,key);unique.set(fingerprint,key);}
 names[key]=unique.get(fingerprint);
}
const source=standaloneCode(ajv,names);
// Bundle all pure runtime helpers now: Workers never compile schemas, eval code,
// load a package, follow a remote $ref or call a network during preflight.
const bundled=await build({absWorkingDir:root,stdin:{contents:source,resolveDir:root,sourcefile:'preflight-standalone.cjs'},bundle:true,platform:'neutral',format:'esm',minify:true,legalComments:'inline',write:false});
const target=new URL('../src/input-validators.js',import.meta.url);
const licenses=['ajv/LICENSE','ajv-formats/LICENSE'].map(path=>'/* '+path+'\n'+readFileSync(new URL('../node_modules/'+path,import.meta.url),'utf8')+' */\n').join('');
const content=licenses+'// Generated by scripts/generate-input-validators.js. No runtime schema compilation or network.\n'+bundled.outputFiles[0].text;
if(/new Function\s*\(|\beval\s*\(/u.test(content)) throw Error('Dynamic code generation in preflight bundle');
if(process.argv.includes('--check')) {
 if(readFileSync(target,'utf8')!==content) {console.error('Input validators are stale; run node scripts/generate-input-validators.js');process.exitCode=1;}
} else {writeFileSync(target,content);console.log(Object.keys(names).length+' static input validators generated');}
