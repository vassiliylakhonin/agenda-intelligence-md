import {build} from 'esbuild';
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const bundle=await build({entryPoints:[new URL('apps/supplier-desk/main.js',root).pathname],bundle:true,
  platform:'browser',format:'iife',target:'es2022',minify:true,write:false});
const content='// Generated by scripts/generate-supplier-desk.js.\nexport const SUPPLIER_DESK_CLIENT='+JSON.stringify(bundle.outputFiles[0].text)+';\n';
const output=new URL('src/supplier-desk-bundle.js',root);
if(process.argv.includes('--check')){
  if(readFileSync(output,'utf8')!==content){console.error('Supplier desk bundle is stale. Run node scripts/generate-supplier-desk.js');process.exitCode=1;}
}else{writeFileSync(output,content);console.log('Bundled local supplier desk.');}
