import {build} from 'esbuild';
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const bundle=await build({entryPoints:[new URL('apps/supplier-desk/main.js',root).pathname],bundle:true,
  platform:'browser',format:'iife',target:'es2022',minify:true,write:false});
const content='// Generated by scripts/generate-supplier-desk.js.\nexport const SUPPLIER_DESK_CLIENT='+JSON.stringify(bundle.outputFiles[0].text)+';\n';
const output=new URL('src/supplier-desk-bundle.js',root);
const worker=await build({entryPoints:[new URL('apps/supplier-desk/document-worker.js',root).pathname],bundle:true,
  platform:'browser',format:'iife',target:'es2022',minify:true,legalComments:'inline',loader:{'.ttf':'binary'},write:false});
const licenses=readFileSync(new URL('apps/supplier-desk/vendor/THIRD-PARTY-LICENSES.txt',root),'utf8');
const workerSource='/*!\n'+licenses.replaceAll('*/','* /')+'\n*/\n'+worker.outputFiles[0].text;
const workerContent='// Generated by scripts/generate-supplier-desk.js. Browser dedicated worker only.\nexport const SUPPLIER_DOCUMENT_WORKER='+JSON.stringify(workerSource)+';\n';
const workerOutput=new URL('src/supplier-document-worker-bundle.js',root);
if(process.argv.includes('--check')){
  if(readFileSync(output,'utf8')!==content){console.error('Supplier desk bundle is stale. Run node scripts/generate-supplier-desk.js');process.exitCode=1;}
  if(readFileSync(workerOutput,'utf8')!==workerContent){console.error('Supplier document worker is stale. Run node scripts/generate-supplier-desk.js');process.exitCode=1;}
}else{writeFileSync(output,content);writeFileSync(workerOutput,workerContent);console.log('Bundled local supplier desk and isolated document processor ('+worker.outputFiles[0].text.length+' bytes).');}
